import {readdir, writeFile} from 'node:fs/promises';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const toolDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(toolDirectory, '../..');
const sampleRoot = join(projectRoot, 'audio/lofi/instruments');
const output = join(projectRoot, 'lofiInstruments.mjs');

const directories = (await readdir(sampleRoot, {withFileTypes: true}))
  .filter(entry => entry.isDirectory())
  .map(entry => entry.name)
  .sort();

const banks = {};
for (const instrument of directories) {
  const files = (await readdir(join(sampleRoot, instrument)))
    .filter(file => /^[A-G]s?\d\.mp3$/.test(file))
    .sort((left, right) => left.localeCompare(right, 'en', {numeric: true}));
  banks[instrument] = {
    baseUrl: `/audio/lofi/instruments/${instrument}/`,
    urls: Object.fromEntries(files.map(file => [file.slice(0, -4).replace('s', '#'), file])),
  };
}

const source = `// Generated by ${relative(projectRoot, fileURLToPath(import.meta.url))}.\n`
  + `// Complete MP3 note set from nbrosowsky/tonejs-instruments.\n`
  + `export const INSTRUMENT_BANKS = ${JSON.stringify(banks, null, 2)};\n\n`
  + `export const INSTRUMENT_ROLES = Object.freeze({\n`
  + `  harmony: ['piano', 'guitar-acoustic', 'guitar-electric', 'guitar-nylon', 'harmonium', 'organ', 'harp', 'xylophone'],\n`
  + `  bass: ['bass-electric', 'contrabass', 'cello', 'bassoon', 'tuba', 'trombone'],\n`
  + `  lead: ['flute', 'clarinet', 'bassoon', 'french-horn', 'saxophone', 'trombone', 'trumpet', 'violin', 'cello', 'guitar-electric', 'harp', 'xylophone'],\n`
  + `  arp: ['guitar-acoustic', 'guitar-electric', 'guitar-nylon', 'harp', 'piano', 'xylophone', 'harmonium'],\n`
  + `  mallet: ['xylophone', 'harp', 'piano', 'guitar-nylon'],\n`
  + `});\n\n`
  + `const ROLE_OFFSETS = {harmony: 24, bass: 32, lead: 40, arp: 48, mallet: 56};\n\n`
  + `export function selectInstrument(hash, role) {\n`
  + `  const choices = INSTRUMENT_ROLES[role];\n`
  + `  if (!choices) throw new TypeError(\`Unknown instrument role: \${role}\`);\n`
  + `  const value = Number.parseInt(String(hash).slice(ROLE_OFFSETS[role], ROLE_OFFSETS[role] + 8), 16);\n`
  + `  return choices[Number.isFinite(value) ? value % choices.length : 0];\n`
  + `}\n\n`
  + `export const instrumentLabel = name => name.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join(' ');\n`;

await writeFile(output, source);
console.log(`Wrote ${relative(projectRoot, output)} with ${directories.length} instruments.`);
