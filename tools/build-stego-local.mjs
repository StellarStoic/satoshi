function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function localPath(webPath) {
  return join(root, webPath.replace(/^\//, ''));
}

function mimeType(path) {
  if (path.endsWith('.png')) return 'image/png';
  if (path.endsWith('.jpg') || path.endsWith('.jpeg')) return 'image/jpeg';
  if (path.endsWith('.svg')) return 'image/svg+xml';
  throw new Error(`No embedded MIME type configured for ${path}`);
}

function dataUri(webPath) {
  return `data:${mimeType(webPath)};base64,${readFileSync(localPath(webPath)).toString('base64')}`;
}

function safeInlineScript(source) {
  return source.replace(/<\/script/gi, '<\\/script');
}

function replaceOnce(source, pattern, replacement, label) {
  const next = source.replace(pattern, () => replacement);
  if (next === source) throw new Error(`Could not locate ${label}`);
  return next;
}

function inlineStyle(html, webPath) {
  let css = readFileSync(localPath(webPath), 'utf8');
  for (const imagePath of embeddedImages) {
    css = css.replaceAll(imagePath, dataUri(imagePath));
  }
  const tag = new RegExp(`<link\\s+rel="stylesheet"\\s+href="${escapeRegExp(webPath)}"\\s*/?>`);
  return replaceOnce(html, tag, `<style data-local-source="${webPath}">\n${css}\n</style>`, webPath);
}

function inlineScript(html, webPath) {
  let js = readFileSync(localPath(webPath), 'utf8');
  for (const imagePath of embeddedImages) {
    js = js.replaceAll(imagePath, dataUri(imagePath));
  }
  const tag = new RegExp(`<script\\s+src="${escapeRegExp(webPath)}"\\s*><\\/script>`);
  return replaceOnce(html, tag, `<script data-local-source="${webPath}">\n${safeInlineScript(js)}\n</script>`, webPath);
}

export function buildStandalone() {
  let html = readFileSync(sourcePath, 'utf8');

  html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by tools/build-stego-local.mjs from stego.html. Do not edit this file directly. -->');
  html = html.replace('<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">', '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n  <meta name="robots" content="noindex, nofollow">');
  html = html.replace('Steganography and Cipher Tools | Satoshi.si', 'Steganography and Cipher Tools | Local Edition');
  html = html.replace(/\s*<link rel="canonical"[^>]*>/, '');
  html = html.replace(/\s*<link rel="icon"[^>]*>/, '');
  html = html.replace(/\s*<link rel="manifest"[^>]*>/, '');
  html = html.replace(/\s*<script src="\/pwa\.js" defer><\/script>/, '');
  html = html.replace(/\s*<script src="\/siteEffects\.js" defer><\/script>/, '');
  html = html.replace(/\s*<script src="\/vendor\/lucide\/lucide\.min\.js" defer><\/script>/, '');
  html = html.replace(/\s*<script src="\/burgerMenu\.js"><\/script>/, '');
  html = html.replace(/\s*<a href="#menu" id="toggle"[\s\S]*?<\/a>\s*<nav id="menu"[\s\S]*?<\/nav>/, '');
  html = html.replace(/\s*<footer class="footer" data-live-footer>[\s\S]*?<\/footer>/, '');

  for (const webPath of styleAssets) html = inlineStyle(html, webPath);
  for (const webPath of scriptAssets) html = inlineScript(html, webPath);

  const utilityScripts = ['/siteEffects.js', '/vendor/lucide/lucide.min.js']
    .map(webPath => `<script data-local-source="${webPath}">\n${safeInlineScript(readFileSync(localPath(webPath), 'utf8'))}\n</script>`)
    .join('\n');
  html = replaceOnce(html, '</body>', `${utilityScripts}\n</body>`, 'closing body tag');

  for (const imagePath of embeddedImages) html = html.replaceAll(imagePath, dataUri(imagePath));

  return html;
}

const built = buildStandalone();
if (process.argv.includes('--check')) {
  const existing = readFileSync(outputPath, 'utf8');
  if (existing !== built) {
    console.error(`${relative(root, outputPath)} is stale. Run node tools/build-stego-local.mjs.`);
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, built);
  console.log(`Built ${relative(root, outputPath)} (${Buffer.byteLength(built).toLocaleString()} bytes).`);
}
